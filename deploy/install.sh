#!/usr/bin/env bash
# Skjald installer — step 1: check the host, install Docker Engine, create the
# directories Skjald needs. Later steps (keys, images, the setup wizard) land
# as the pieces they depend on are built; see docs/architecture.md.
set -euo pipefail

SKJALD_HOME="/opt/skjald"
SKJALD_ETC="/etc/skjald"
MIN_CPU=4
MIN_RAM_MB=7800
MIN_DISK_GB=90

log() { printf '==> %s\n' "$1"; }
warn() { printf 'WARNING: %s\n' "$1" >&2; }
die() {
	printf 'ERROR: %s\n' "$1" >&2
	exit 1
}

if [[ "${EUID}" -ne 0 ]]; then
	die "Run this installer as root (sudo)."
fi

check_os() {
	if [[ ! -r /etc/os-release ]]; then
		die "Cannot read /etc/os-release; this installer targets Ubuntu Server LTS."
	fi
	# shellcheck source=/dev/null
	. /etc/os-release
	if [[ "${ID:-}" != "ubuntu" ]]; then
		die "Skjald targets Ubuntu Server LTS; found ID=${ID:-unknown}."
	fi
	log "OS: ${PRETTY_NAME:-Ubuntu}"
}

check_resources() {
	local cpu ram_mb disk_gb
	cpu=$(nproc)
	ram_mb=$(awk '/MemTotal/ {printf "%d", $2/1024}' /proc/meminfo)
	disk_gb=$(df -BG --output=avail / | tail -1 | tr -dc '0-9')

	log "Resources: ${cpu} vCPU, ${ram_mb} MB RAM, ${disk_gb} GB free on /."

	[[ "${cpu}" -lt "${MIN_CPU}" ]] && warn "Fewer than ${MIN_CPU} vCPU; Skjald will be slow under load."
	[[ "${ram_mb}" -lt "${MIN_RAM_MB}" ]] && warn "Less than ~8 GB RAM; ClamAV alone needs about 2 GB."
	[[ "${disk_gb}" -lt "${MIN_DISK_GB}" ]] && warn "Less than ${MIN_DISK_GB} GB free; grow the disk before storing real data."
}

install_docker() {
	if command -v docker >/dev/null 2>&1; then
		log "Docker is already installed."
		return
	fi
	log "Installing Docker Engine from Docker's own repository."
	install -m 0755 -d /etc/apt/keyrings
	curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
	chmod a+r /etc/apt/keyrings/docker.asc
	# shellcheck source=/dev/null
	. /etc/os-release
	echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu ${VERSION_CODENAME} stable" \
		>/etc/apt/sources.list.d/docker.list
	apt-get update -qq
	apt-get install -y -qq docker-ce docker-ce-cli containerd.io docker-compose-plugin
}

create_directories() {
	install -d -m 0750 "${SKJALD_HOME}"
	# Owned by the app container's non-root UID, not actual root: the app
	# reads the master key directly, and it never runs as root (see
	# docs/architecture.md's hardening section).
	install -d -o 10001 -g 10001 -m 0700 "${SKJALD_ETC}"
	log "Created ${SKJALD_HOME} and ${SKJALD_ETC}."
}

generate_master_key() {
	local key_file="${SKJALD_ETC}/master.key"
	if [[ -f "${key_file}" ]]; then
		log "Master key already exists; leaving it alone."
		return
	fi
	log "Generating the master key."
	(umask 077 && head -c 32 /dev/urandom >"${key_file}")
	chown 10001:10001 "${key_file}"
	chmod 0600 "${key_file}"
}

check_os
check_resources
install_docker
create_directories
generate_master_key

log "Host prepared. The database and backup keys are generated by the app on first start."
log "The setup wizard is not wired up yet."
